LEFT JOIN FISHSTAT.REF_INLAND_MARINE m ON m.ID = ia.PARENT_ID
WHERE g.ID IN ('00000002', '00000003')
GROUP BY g.ID, COALESCE(g.NAME_EN, 'Unknown'), COALESCE(m.NAME_EN, 'Other')
