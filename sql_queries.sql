                  WHERE y.PARENT_ID = '00000004' AND y.CHILD_ID = s.ID)
GROUP BY ig.NAME_EN, (((ig.CODE - ig.CODE / 10 * 10) + 10 * ((ig.CODE - ig.CODE / 100 * 100) / 10))), ig.ID
ORDER BY 2

