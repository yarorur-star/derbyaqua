-- ============================================================================
-- sql_queries.sql — SQL-запросы в диалекте Apache Derby (embedded) для
-- формирования таблиц 1-9 задания "derbyaqua" (данные ФАО по аквакультуре,
-- схема FISHSTAT, дампы из /CSV).
--
-- Общие правила (см. README.md):
--   * Последние 5 лет данных базы: 2020-2024 (поля VALUE_Y2020..VALUE_Y2024).
--   * "К" = количество в тоннах (TSD_AQUACULTURE_QUANTITY, мера Q_tlw),
--     "С" = стоимость в тыс.долларов (TSD_AQUACULTURE_VALUE, мера V_USD_1000).
--   * Группа REF_YEARBOOK_GROUP ID 00000001 ("All aquatic organisms") игнорируется;
--     виды группы ID 00000004 ("Other aquatic animals & products") ИСКЛЮЧАЮТСЕСЯ
--     из расчетов; используются виды групп 00000002 и 00000003.
--     Исключение реализовано условием NOT EXISTS по REL_YEARBOOK_GROUP_SPECIES
--     с PARENT_ID='00000004'.
--   * Используются только поля _EN; имена стран/видов — как в базе, без изменений.
--   * Диалект Derby: SUM(CASE...), COALESCE, скалярные подзапросы, NOT EXISTS;
--     сортировка по позициям SELECT-списка.
--
-- Разделители запросов: строка, состоящая ровно из "-- @QUERY <имя>".
-- Текст одного запроса не содержит символа ';' до конца запроса.
-- ============================================================================

-- @QUERY t1_countries_quantity
-- Таблица 1. Производство аквакультуры странами, тонн.
-- Колонки: страна, 2020, 2021, 2022, 2023, 2024.
SELECT COALESCE(c.NAME_EN, 'Unknown') AS COUNTRY_NAME,
       SUM(COALESCE(t.VALUE_Y2020, 0)) AS Y2020,
       SUM(COALESCE(t.VALUE_Y2021, 0)) AS Y2021,
       SUM(COALESCE(t.VALUE_Y2022, 0)) AS Y2022,
       SUM(COALESCE(t.VALUE_Y2023, 0)) AS Y2023,
       SUM(COALESCE(t.VALUE_Y2024, 0)) AS Y2024
FROM FISHSTAT.TSD_AQUACULTURE_QUANTITY t
LEFT JOIN FISHSTAT.REF_COUNTRY c ON c.UN_CODE = t.COUNTRY
WHERE NOT EXISTS (SELECT 1 FROM FISHSTAT.REL_YEARBOOK_GROUP_SPECIES r
                  JOIN FISHSTAT.REF_SPECIES s ON s.ID = r.CHILD_ID
                  WHERE r.PARENT_ID = '00000004' AND s.ALPHA_3_CODE = t.SPECIES)
GROUP BY COALESCE(c.NAME_EN, 'Unknown')
ORDER BY 1

-- @QUERY t2_species_quantity
-- Таблица 2. Производство объектов аквакультуры, тонн.
-- Колонки: вид (NAME_EN), 2020..2024.
SELECT COALESCE(s.NAME_EN, 'Unknown') AS SPECIES_NAME,
       SUM(COALESCE(t.VALUE_Y2020, 0)) AS Y2020,
       SUM(COALESCE(t.VALUE_Y2021, 0)) AS Y2021,
       SUM(COALESCE(t.VALUE_Y2022, 0)) AS Y2022,
       SUM(COALESCE(t.VALUE_Y2023, 0)) AS Y2023,
       SUM(COALESCE(t.VALUE_Y2024, 0)) AS Y2024
FROM FISHSTAT.TSD_AQUACULTURE_QUANTITY t
LEFT JOIN FISHSTAT.REF_SPECIES s ON s.ALPHA_3_CODE = t.SPECIES
WHERE NOT EXISTS (SELECT 1 FROM FISHSTAT.REL_YEARBOOK_GROUP_SPECIES r
                  WHERE r.PARENT_ID = '00000004' AND r.CHILD_ID = s.ID)
GROUP BY COALESCE(s.NAME_EN, 'Unknown')
ORDER BY 1

-- @QUERY t3_world_group_env_quantity
-- Таблица 3 (часть "К"). Мировое производство по группам REF_YEARBOOK_GROUP
-- (00000002, 00000003) и водам (REF_INLAND_MARINE через REL_INLAND_MARINE_AREA), тонн.
SELECT g.ID AS GROUP_ID,
       COALESCE(g.NAME_EN, 'Unknown') AS GROUP_NAME,
       COALESCE(m.NAME_EN, 'Other') AS WATERS_NAME,
       SUM(COALESCE(t.VALUE_Y2020, 0)) AS Y2020,
       SUM(COALESCE(t.VALUE_Y2021, 0)) AS Y2021,
       SUM(COALESCE(t.VALUE_Y2022, 0)) AS Y2022,
       SUM(COALESCE(t.VALUE_Y2023, 0)) AS Y2023,
       SUM(COALESCE(t.VALUE_Y2024, 0)) AS Y2024
FROM FISHSTAT.TSD_AQUACULTURE_QUANTITY t
JOIN FISHSTAT.REF_SPECIES s ON s.ALPHA_3_CODE = t.SPECIES
JOIN FISHSTAT.REL_YEARBOOK_GROUP_SPECIES r ON r.CHILD_ID = s.ID
JOIN FISHSTAT.REF_YEARBOOK_GROUP g ON g.ID = r.PARENT_ID
LEFT JOIN FISHSTAT.REL_INLAND_MARINE_AREA ia ON ia.CHILD_ID =
       (SELECT a.ID FROM FISHSTAT.REF_AREA a WHERE a.CODE = t.AREA)
LEFT JOIN FISHSTAT.REF_INLAND_MARINE m ON m.ID = ia.PARENT_ID
WHERE g.ID IN ('00000002', '00000003')
GROUP BY g.ID, COALESCE(g.NAME_EN, 'Unknown'), COALESCE(m.NAME_EN, 'Other')
ORDER BY 1, 2

